// Everything cache-keeper says, in each language it speaks. The band's title is
// one word, not a translation: each language's own word for something left to
// cook (English "Cooking").
// Commands are typed in English everywhere (Russian and Ukrainian words work
// too); the Russian texts show the Russian words.

import type { Display } from '../types'
import type { Lang } from './i18n'

export type Strings = {
  cmdDescription: string
  argHint: string
  /** The band's title: the kitchen is busy. */
  title: string
  timeLeft: (d: string) => string
  demoSub: (tally: string) => string
  tally: (served: number, total: number, left: number) => string
  kitchenAlt: (tally: string) => string
  statusLine: (d: string) => string
  offState: string
  onState: (d: string) => string
  lastRequest: (since: string, cache: string) => string
  unknown: string
  ago: (d: string) => string
  warmFor: (d: string) => string
  cold: string
  warmUps: (count: number, last: string | null) => string
  guests: (tally: string) => string
  indicator: (name: string) => string
  commands: string
  displayNames: Record<Display, string>
  noteRead: (k: string) => string
  noteCold: (k: string) => string
  noteNothing: string
  noteFailed: (reason: string, d: string) => string
  toastCold: string
  /** Warming came back on after the session's process stopped and started again (the mod cannot tell why). */
  resumed: (cold: boolean) => string
  /** The status line: how many such restarts warming went through. */
  pauses: (n: number) => string
  toastEnded: (d: string, tally: string) => string
  displayNow: (name: string) => string
  displayWrong: (word: string) => string
  displaySet: (name: string) => string
  demoNotRunning: string
  demoStopped: string
  demoStarted: (guests: number, seconds: number) => string
  demoEnded: (tally: string) => string
  alreadyOff: string
  turnedOff: string
  notUnderstood: (args: string) => string
  badHours: (word: string) => string
  turnedOn: (d: string, quiet: string) => string
  alreadyCold: string
  howToOff: string
  guardWarning: (ago: string, k: string) => string
  guardDrop: (warning: string) => string
}

